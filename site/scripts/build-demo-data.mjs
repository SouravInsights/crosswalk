// Builds the landing page demo from a real OpenAPI spec excerpt, by running
// the actual webmcp-codegen pipeline in dry-run mode. What the page shows is
// what the CLI produces, because the CLI produced it.
//
// Run after changing site/demo/immich-excerpt.openapi.yaml or the generator:
//   node scripts/build-demo-data.mjs        (from site/)

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { runGenerate } from "../../packages/codegen/dist/index.js";
import { js } from "../../packages/codegen/dist/generators/index.js";
import { openapi } from "../../packages/codegen/dist/sources/index.js";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");

const report = await runGenerate(
  {
    sources: [openapi({ spec: "demo/immich-excerpt.openapi.yaml" })],
    generate: [js({ outDir: "src/webmcp" })],
  },
  { cwd: site, write: false, skipAudit: false, force: true },
);

// Tool files only. The barrel (index.ts) and runtime helper are noise here.
const toolFiles = new Map(
  report.files
    .filter((f) => f.path.endsWith(".webmcp.ts") && !f.path.endsWith("runtime.webmcp.ts"))
    .map((f) => [f.path.split("/").pop().replace(/\.webmcp\.ts$/, ""), f.contents]),
);

const tools = report.tools.map((tool) => {
  const [verb, ...rest] = tool.source.ref.split(" ");
  const contents = toolFiles.get(tool.name);
  if (!contents) throw new Error(`No generated file found for ${tool.name}`);
  return {
    name: tool.name,
    verb,
    path: rest.join(" "),
    summary: tool.description,
    sideEffect: tool.sideEffect,
    fileName: `${tool.name}.webmcp.ts`,
    fileCode: contents,
    findings: report.findings
      .filter((f) => f.tool === tool.name)
      .map((f) => ({ severity: f.level, message: f.message })),
  };
});

const out = `// Generated by site/scripts/build-demo-data.mjs from the real
// webmcp-codegen pipeline. Do not edit by hand; re-run the script instead.

export interface DemoTool {
  name: string;
  verb: string;
  path: string;
  summary: string;
  sideEffect: "read" | "write" | "destructive";
  fileName: string;
  fileCode: string;
  findings: Array<{ severity: "warning" | "error"; message: string }>;
}

export const DEMO_SOURCE = {
  project: "Immich",
  blurb: "the open-source photo app",
  specUrl: "https://github.com/immich-app/immich/blob/main/open-api/immich-openapi-specs.json",
};

export const DEMO_TOOLS: DemoTool[] = ${JSON.stringify(tools, null, 2)};
`;

await writeFile(join(site, "lib/demo-data.ts"), out);
console.log(`Wrote lib/demo-data.ts with ${tools.length} tools from the Immich excerpt.`);
